#!/usr/bin/env node
/**
 * Pre-compute lightweight curriculum stats so the home page doesn't have
 * to ship the entire 230 KB module/course metadata blob.
 *
 * Output: lib/curriculum-stats.ts
 *
 * What's precomputed:
 *   SECTION_TOTAL_COURSES — { [sectionId]: number }
 *     Total course count per section. Used by home's SectionCards to
 *     show "X / Y courses completed" without iterating modules.
 *
 *   SECTION_COURSE_IDS — { [sectionId]: string[] }
 *     Course IDs per section. Home uses this to compute completedCount
 *     by intersecting with the user's `completedCourses` array. Cheap
 *     because it's just strings, no descriptions / tags / objects.
 *
 * Run: as part of prebuild (`npm run prebuild`). The output file is
 * gitignored — regenerated from `lib/curriculum.ts` on every build.
 *
 * Why a build-time script and not a runtime helper:
 * - At runtime we'd still need the full curriculum.ts module loaded to
 *   compute these numbers, defeating the purpose.
 * - Pre-computing at build time means the home bundle ships ~10 KB of
 *   precomputed lookups instead of 230 KB of full structure.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const CURRICULUM_TS = join(ROOT, 'lib', 'curriculum.ts');
const OUT = join(ROOT, 'lib', 'curriculum-stats.ts');

if (!existsSync(CURRICULUM_TS)) {
  console.error(`[build-curriculum-stats] missing ${CURRICULUM_TS}`);
  process.exit(0);
}

// Strategy: compile-on-the-fly via tsx is heavy. Cheaper to pull the
// text and walk the export AST with a regex-based parser — we only need
// `id`, `sectionId`, `courses[].id`. The full curriculum.ts is regular
// (auto-generated from data); regex matching is reliable here.

const src = readFileSync(CURRICULUM_TS, 'utf8');

/* Match every Module literal:
 *   { id: <num>, sectionId: '<id>', title: ..., description: ...,
 *     color: ..., courses: [...] }
 *
 * We just need (sectionId, courses[].id). The courses array can have
 * many items, each `{ id: '<id>', ... }`. */
// Match each Module literal. Two formats appear in curriculum.ts:
//   `{ id: 100, sectionId: 'fundamentals', ..., courses: [c('100.1', ...), c('100.2', ...), ...] }`
//
// The course IDs are the first arg of the `c('id', moduleId, ...)` helper.
// Match each Module literal — capture id, sectionId, title, description,
// color, and the courses[] block.
const moduleRegex = /\{\s*id:\s*(\d+)\s*,\s*sectionId:\s*'([a-z]+)'\s*,\s*title:\s*'([^']+)'\s*,\s*color:\s*'([^']+)'\s*,\s*description:\s*'([^']+)'\s*,\s*courses:\s*\[([\s\S]+?)\]\s*,?\s*\}/g;
// First positional arg of c(): a single-quoted string that's the course id.
const courseIdRegex = /\bc\(\s*'([^']+)'/g;

const sectionTotals = {};
const sectionCourseIds = {};
const moduleMeta = {};
const moduleCourseIds = {};

// Pull the `sections` array source verbatim — it's small (~3.6 KB) and
// home renders all 12 of them. Including it here means app/page.tsx
// never has to import lib/curriculum.ts (which would drag in the
// full 230 KB module data via webpack's import graph).
const sectionsBlockMatch = /export\s+const\s+sections:\s*Section\[\]\s*=\s*(\[[\s\S]+?\n\]);/m.exec(src);
const sectionsLiteral = sectionsBlockMatch ? sectionsBlockMatch[1] : null;
if (!sectionsLiteral) {
  console.warn('[build-curriculum-stats] WARN: could not locate `sections` array — output will lack SECTIONS');
}

let match;
let modulesFound = 0;
while ((match = moduleRegex.exec(src)) !== null) {
  modulesFound++;
  const moduleId = parseInt(match[1], 10);
  const sectionId = match[2];
  const title = match[3];
  const color = match[4];
  const description = match[5];
  const coursesBlock = match[6];

  const courseIds = [];
  let courseMatch;
  while ((courseMatch = courseIdRegex.exec(coursesBlock)) !== null) {
    courseIds.push(courseMatch[1]);
  }
  courseIdRegex.lastIndex = 0;

  if (!sectionTotals[sectionId]) sectionTotals[sectionId] = 0;
  sectionTotals[sectionId] += courseIds.length;
  if (!sectionCourseIds[sectionId]) sectionCourseIds[sectionId] = [];
  for (const cid of courseIds) sectionCourseIds[sectionId].push(cid);

  moduleMeta[moduleId] = { sectionId, title, color, description };
  moduleCourseIds[moduleId] = courseIds.slice();
}

if (modulesFound === 0) {
  console.warn('[build-curriculum-stats] WARN: 0 modules parsed — regex may need updating');
  process.exit(0);
}

const totalCourses = Object.values(sectionTotals).reduce((s, n) => s + n, 0);

const lines = [];
lines.push('/* AUTO-GENERATED by scripts/build-curriculum-stats.mjs.');
lines.push(' * DO NOT EDIT BY HAND. Regenerated on every prebuild from lib/curriculum.ts.');
lines.push(' *');
lines.push(' * Why this file exists:');
lines.push(' *   The home page renders 12 section cards, each showing "X / Y courses');
lines.push(' *   completed". Computing X and Y at runtime requires iterating the full');
lines.push(' *   modules array (~230 KB raw). Pre-computing lookups at build time keeps');
lines.push(' *   the home bundle small.');
lines.push(' */');
lines.push('import type { SectionId, Section } from \'./curriculum-types\';');
lines.push('');
if (sectionsLiteral) {
  lines.push('/** Section metadata array. Inlined here so consumers can import this');
  lines.push(' *  one tiny file instead of pulling in lib/curriculum.ts (which drags');
  lines.push(' *  the entire 230 KB module data into webpack\'s graph).');
  lines.push(' */');
  lines.push(`export const SECTIONS: Section[] = ${sectionsLiteral};`);
  lines.push('');
  lines.push('/** O(1) section lookup by id. */');
  lines.push('export function getSectionByIdFast(id: SectionId): Section | undefined {');
  lines.push('  return SECTIONS.find((s) => s.id === id);');
  lines.push('}');
  lines.push('');
}
lines.push('/** Total course count per section. */');
lines.push('export const SECTION_TOTAL_COURSES: Record<SectionId, number> = {');
for (const [sid, total] of Object.entries(sectionTotals)) {
  lines.push(`  ${sid}: ${total},`);
}
lines.push('};');
lines.push('');
lines.push('/** Course IDs per section, for intersecting with the user\'s completedCourses. */');
lines.push('export const SECTION_COURSE_IDS: Record<SectionId, readonly string[]> = {');
for (const [sid, ids] of Object.entries(sectionCourseIds)) {
  lines.push(`  ${sid}: [`);
  // Pack 4 IDs per line for diff-friendliness.
  for (let i = 0; i < ids.length; i += 4) {
    const chunk = ids.slice(i, i + 4).map((s) => `'${s}'`).join(', ');
    lines.push(`    ${chunk},`);
  }
  lines.push('  ],');
}
lines.push('};');
lines.push('');
lines.push('/** Module metadata only (title + description + color + sectionId).');
lines.push(' *  No course list. Home/section views use this to render headers without');
lines.push(' *  pulling the full courses array (which is heavy — that\'s in lib/curriculum.ts).');
lines.push(' */');
lines.push('export interface ModuleMeta {');
lines.push('  sectionId: SectionId;');
lines.push('  title: string;');
lines.push('  color: string;');
lines.push('  description: string;');
lines.push('}');
lines.push('/** Course IDs per module. Used by lib/store.ts isModuleTestUnlocked');
lines.push(' *  without dragging the full Course objects into the home bundle. */');
lines.push('export const MODULE_COURSE_IDS: Record<number, readonly string[]> = {');
for (const [mid, ids] of Object.entries(moduleCourseIds).sort((a, b) => Number(a[0]) - Number(b[0]))) {
  const inline = ids.map((s) => `'${s}'`).join(', ');
  lines.push(`  ${mid}: [${inline}],`);
}
lines.push('};');
lines.push('');
lines.push('export const MODULE_META: Record<number, ModuleMeta> = {');
for (const [mid, meta] of Object.entries(moduleMeta).sort((a, b) => Number(a[0]) - Number(b[0]))) {
  // Escape single quotes in strings.
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  lines.push(`  ${mid}: { sectionId: '${meta.sectionId}', title: '${esc(meta.title)}', color: '${meta.color}', description: '${esc(meta.description)}' },`);
}
lines.push('};');
lines.push('');
lines.push(`/** Sanity total for sanity-tests. Built from ${modulesFound} modules / ${totalCourses} courses. */`);
lines.push(`export const TOTAL_COURSES_BUILD: number = ${totalCourses};`);
lines.push('');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(`[build-curriculum-stats] wrote ${OUT}`);
console.log(`  ${modulesFound} modules, ${totalCourses} courses`);
console.log(`  output size: ${(readFileSync(OUT).length / 1024).toFixed(1)} KB`);
