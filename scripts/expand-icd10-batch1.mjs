let added = 0;
let skipped = 0;
const validChapters = new Set(d.chapters.map(c => c.id));
for (const [code, title, chapter] of NEW_CODES) {
  if (existing.has(code)) { skipped++; continue; }
  if (!validChapters.has(chapter)) { console.error('Bad chapter:', chapter, code); continue; }
  d.codes.push({ code, title, chapter });
  existing.add(code);
  added++;
}

// Sort codes by chapter then code (alphanumeric)
d.codes.sort((a, b) => {
  if (a.chapter !== b.chapter) {
    const ai = d.chapters.findIndex(c => c.id === a.chapter);
    const bi = d.chapters.findIndex(c => c.id === b.chapter);
    return ai - bi;
  }
  return a.code.localeCompare(b.code, 'en');
});

