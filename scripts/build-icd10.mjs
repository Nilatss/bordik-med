/**
 * Расширение МКБ-10 базы из data/icd10-starter.json до полных ~14 000
 * кодов в data/icd10-full.json.
 *
 * СТАТУС: ЗАГЛУШКА. Использовать после согласования источника данных.
 *
 * Где брать данные
 * ----------------
 * Полная МКБ-10 в редакции ВОЗ распространяется WHO под открытой
 * лицензией для некоммерческого использования. Несколько вариантов:
 *
 *   1. WHO API: https://icd.who.int/icdapi (требует регистрации,
 *      возвращает JSON по главам). Русский перевод доступен.
 *
 *   2. Минздрав РФ: https://mkb10.com — HTML-источник с полной базой.
 *      Парсинг через cheerio (есть в node_modules).
 *
 *   3. GitHub: несколько публичных дампов МКБ-10 в JSON, например
 *      `mkb-10` npm пакет — но качество перевода непостоянное,
 *      рекомендую сверять с официальным.
 *
 * Что делает скрипт после реализации
 * ----------------------------------
 *   1. Загружает официальные данные (источник на выбор)
 *   2. Нормализует в единый JSON формат: { version, lastUpdated,
 *      chapters[], codes[] }
 *   3. Сверяет каждый код стартовой базы с полной — те, что
 *      отсутствуют, помечает в логах для ручной проверки
 *   4. Записывает в data/icd10-full.json
 *
 * Подключение к runtime
 * ---------------------
 * Когда полная база появится, app/icd10/page.tsx переключится с
 * icd10-starter.json на icd10-full.json. Клиентский компонент
 * Icd10Lookup переключится с linear filter на MiniSearch index
 * (порог переключения — ~1 500 кодов).
 *
 * См. docs/CONTENT_ROADMAP.md, фича #3.
 */
