#!/usr/bin/env node
/**
 * P0-CR-2 — auto-generate basic smoke tests для всех runners БЕЗ
 * существующих тестов в tests/calculators/.
 *
 * Каждый smoke test проверяет:
 *   1. Runner exports default
 *   2. shape: kind 'score' | 'calculator', есть inputs
 *   3. Для 'calculator' — compute() возвращает {value, interpretation, color}
 *      при первой попытке с дефолтными значениями
 *   4. Для 'score' — есть bands, maxScore число
 *
 * Это НЕ замена доменных golden-tests (BMI, GFR, и т.д.) — это smoke
 * coverage: ловит регрессии «runner вообще не запускается» и rough
 * shape mismatch. Доменные тесты пишутся отдельно с clinical input
 * vs expected output cases.
 *
 * Generated tests live в tests/calculators/auto/<id>.test.ts —
 * отдельная директория, чтобы случайно не перезаписать ручные тесты
 * в tests/calculators/<id>.test.ts.
 *
 * Usage: node scripts/gen-smoke-tests.mjs
 */

import { readdirSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RUNNERS_DIR = join(ROOT, 'lib', 'runners');
const HAND_TESTS = join(ROOT, 'tests', 'calculators');
const AUTO_TESTS = join(ROOT, 'tests', 'calculators', 'auto');

if (!existsSync(AUTO_TESTS)) mkdirSync(AUTO_TESTS, { recursive: true });

// Collect runners
const runnerIds = readdirSync(RUNNERS_DIR)
  .filter((f) => f.endsWith('.ts') && !f.startsWith('index') && !f.startsWith('_'))
  .map((f) => f.replace(/\.ts$/, ''));

// Collect existing hand-tests (skip files in auto/ subdirectory)
const handTested = new Set(
  readdirSync(HAND_TESTS)
    .filter((f) => f.endsWith('.test.ts'))
    .map((f) => f.replace(/\.test\.ts$/, ''))
);

let generated = 0;
let skipped = 0;

for (const id of runnerIds) {
  if (handTested.has(id)) {
    skipped++;
    continue;
  }
  const safeId = id.replace(/[^a-z0-9-]/gi, '_');
  // Sanitize import path — runners with `_` not used, but be safe.
  const testPath = join(AUTO_TESTS, `${id}.test.ts`);
  // Already-generated → skip (idempotent re-run)
  if (existsSync(testPath)) {
    skipped++;
    continue;
  }

  const content = `/**
 * P0-CR-2 auto-generated smoke test for runner '${id}'.
 *
 * Проверяет, что runner экспортирует валидный default + has expected
 * shape (kind, inputs) AND что compute() не падает на дефолтных входах
 * и возвращает {value} (для калькуляторов и score-runners с custom
 * compute). НЕ проверяет clinical correctness — для этого пишите
 * hand-test в tests/calculators/${id}.test.ts (если будет, то этот
 * auto-test ИГНОРИРУЕТСЯ генератором).
 *
 * Generated by scripts/gen-smoke-tests.mjs. Не редактируй вручную —
 * regenerate'ится при следующем запуске.
 */
import { describe, it, expect } from 'vitest';
import runner from '@/lib/runners/${id}';
import { buildSmokeDefaults } from '@/tests/helpers/smoke-defaults';

describe('runner:${id} smoke', () => {
  it('exports default', () => {
    expect(runner).toBeDefined();
    expect(runner).not.toBeNull();
  });

  it('has valid kind', () => {
    expect((runner as { kind?: string }).kind).toMatch(/^(score|calculator)$/);
  });

  it('has inputs array', () => {
    const r = runner as { inputs?: unknown[] };
    expect(Array.isArray(r.inputs)).toBe(true);
  });

  it('has reference string (если калькулятор)', () => {
    const r = runner as { kind?: string; reference?: string };
    if (r.kind === 'calculator' || r.kind === 'score') {
      // reference опционален в типе но рекомендуем для citation
      if (r.reference !== undefined) {
        expect(typeof r.reference).toBe('string');
      }
    }
  });

  it('compute() runs on default inputs and returns a defined value', () => {
    // Behavioural smoke: builds a default input map (preset[0] if present,
    // else per-input sensible defaults) and calls compute(). Only runs when
    // a compute fn exists — pure band-based scores have none.
    const r = runner as {
      kind?: string;
      inputs?: unknown[];
      presets?: { values?: Record<string, unknown> }[];
      compute?: (v: Record<string, number | boolean | string>) => { value?: unknown };
    };
    if (typeof r.compute !== 'function') {
      // band-based score with no custom compute — nothing behavioural to smoke
      expect(r.kind).toBe('score');
      return;
    }
    const defaults = buildSmokeDefaults(r.inputs, r.presets);
    let result: { value?: unknown } | undefined;
    expect(() => { result = r.compute!(defaults); }).not.toThrow();
    expect(result).toBeDefined();
    expect(result).not.toBeNull();
    expect(result!.value).toBeDefined();
  });
});
`;
  writeFileSync(testPath, content, 'utf8');
  generated++;
}

console.log(`✓ generated ${generated} smoke tests`);
console.log(`  skipped ${skipped} (hand-tested or already generated)`);
console.log(`  total runners: ${runnerIds.length}`);
