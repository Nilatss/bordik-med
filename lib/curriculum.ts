/** Flat searchable index of all courses with their module & section context */
export interface SearchableCourse {
  course: Course;
  module: Module;
  section: Section | undefined;
  haystack: string; // pre-lowered string used for matching
}

let _searchIndex: SearchableCourse[] | null = null;
export function getCourseSearchIndex(): SearchableCourse[] {
  if (_searchIndex) return _searchIndex;
  const idx: SearchableCourse[] = [];
  for (const m of modules) {
    const section = getSectionById(m.sectionId);
    for (const c of m.courses) {
      const hay = [
        c.id,
        c.title,
        c.description,
        ...(c.tags || []),
        m.title,
        section?.title || '',
      ].join(' ').toLowerCase();
      idx.push({ course: c, module: m, section, haystack: hay });
    }
  }
  _searchIndex = idx;
  return idx;
}

/** Simple relevance search - returns up to `limit` best-matching courses.
 *  `preferSectionId` boosts courses from the section the user is currently
 *  browsing so context-relevant hits float to the top. */
export function searchCourses(
  query: string,
  limit = 20,
  preferSectionId?: string,
): SearchableCourse[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const tokens = q.split(/\s+/).filter(Boolean);
  const idx = getCourseSearchIndex();

  const scored: { item: SearchableCourse; score: number }[] = [];
  for (const item of idx) {
    let score = 0;
    for (const tok of tokens) {
      if (!item.haystack.includes(tok)) { score = -1; break; }
      // Title prefix is the strongest signal (user usually types the start)
      if (item.course.title.toLowerCase().startsWith(tok)) score += 6;
      // Boost if match is anywhere in title
      if (item.course.title.toLowerCase().includes(tok)) score += 3;
      // Boost if exact word match
      const re = new RegExp(`\\b${tok.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`);
      if (re.test(item.haystack)) score += 2;
      // Boost for tag match
      if ((item.course.tags || []).some((t) => t.toLowerCase().includes(tok))) score += 2;
      // Base hit
      score += 1;
    }
    if (score > 0) {
      // Section context boost — keeps the user inside their current section.
      if (preferSectionId && item.module.sectionId === preferSectionId) score += 4;
      scored.push({ item, score });
    }
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.item);
}

