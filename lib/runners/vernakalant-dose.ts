        'НЕ применять при: САД < 100 мм рт.ст., тяжёлом аортальном стенозе, ОКС в течение 30 дней, NYHA III–IV, удлинении QT > 440 мс, тяжёлой брадикардии, СССУ без ЭКС, АВ-блокаде II–III ст. без ЭКС.',
        'Не применять при ФП > 7 сут (низкая эффективность, повышен риск).',
        'Не применять одновременно с другими антиаритмиками класса I и III (амиодарон) в первые 4 ч до и 4 ч после.',
