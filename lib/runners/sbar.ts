/** Runner: sbar - SBAR structured communication */
import type {
  CalculatorTool, ToolInput, Preset, CalculatorResult, ResultExtras, ResultScaleSegment,
} from '../tools-runners';

const runner: CalculatorTool = {
  kind: 'calculator',
  inputs: [
    {
      id: 'scenario',
      label: 'Клинический сценарий',
      type: 'select',
      options: [
        { value: 'deterioration', label: 'Ухудшение состояния пациента' },
        { value: 'handover', label: 'Передача смены / перевод' },
        { value: 'consult', label: 'Телефонный консилиум / вызов специалиста' },
        { value: 'medication', label: 'Уточнение по препарату' },
        { value: 'discharge', label: 'Выписка / перевод в амбулаторию' },
      ],
    },
    {
      id: 'urgency',
      label: 'Срочность',
      type: 'select',
      options: [
        { value: 'emergent', label: 'Экстренно (<5 мин)' },
        { value: 'urgent', label: 'Срочно (<30 мин)' },
        { value: 'routine', label: 'Плановая' },
      ],
    },
  ],
  compute: (v) => {
    const sc = String(v.scenario || 'deterioration');
    const urg = String(v.urgency || 'routine');

    const templates: Record<string, { s: string; b: string; a: string; r: string }> = {
      deterioration: {
        s: '"Я звоню по поводу [ФИО, возраст, палата]. Состояние ухудшилось: [ЧСС, АД, SpO2, сознание, жалобы]."',
        b: '"Диагноз: [...]. Поступил [дата]. Актуальная терапия: [...]. Аллергия: [...]. Значимый анамнез: [...]."',
        a: '"Я думаю, у пациента [рабочий диагноз / возможный сепсис / ОКС / TIA]. Я обеспокоен тем, что [конкретно]."',
        r: '"Я прошу вас: 1) осмотреть в течение X минут; 2) назначить [...]; 3) перевести в ICU. Сохранится ли текущий план если ничего не меняется?"',
      },
      handover: {
        s: '"Передаю смену. Пациент [ФИО, палата], диагноз [...], состояние стабильное/нестабильное."',
        b: '"Ключевое: [операции / процедуры за смену, изменения терапии, результаты значимых анализов]."',
        a: '"Мои опасения: [красные флаги, ожидаемые осложнения]. Что ожидать в ближайшие часы: [...]."',
        r: '"Контроль: [параметры + частота]. План: [назначенные назначения на следующую смену]. Эскалация при: [конкретные триггеры]."',
      },
      consult: {
        s: '"[ФИО, специальность консультанта]. Я [ФИО, должность]. Пациент [ФИО, возраст, палата] — консультация нужна по поводу [...]."',
        b: '"Основной диагноз, коморбидности, текущая терапия, ключевые результаты обследования."',
        a: '"Моя оценка: [дифф. диагноз / рабочая гипотеза]. Конкретный вопрос к вам: [...]."',
        r: '"Прошу: 1) осмотреть [срок]; 2) рекомендации по [...]; 3) решение о переводе/операции."',
      },
      medication: {
        s: '"По препарату [МНН] у пациента [возраст, палата]."',
        b: '"Показание: [...]. Сопутствующее: СКФ [...], печёночная функция [...], другие препараты [...]."',
        a: '"Моё предположение: [доза X / замена на Y / отмена из-за взаимодействия]."',
        r: '"Прошу подтвердить дозировку / интервал / альтернативу / необходимость мониторинга."',
      },
      discharge: {
        s: '"Выписка пациента [ФИО, возраст]. Находился с [дата] по [дата] с диагнозом [...]."',
        b: '"Проведено: [ключевые процедуры / операции]. Результаты: [...]."',
        a: '"Состояние при выписке: [...]. Основные риски: [повторная госпитализация, ТЭЛА, падения]."',
        r: '"План: 1) препараты [список со строкой]; 2) контрольные визиты [когда, к кому]; 3) красные флаги [...]; 4) обследование через [срок]."',
      },
    };

    const t = templates[sc]!;
    let color = '#22C55E', band = 'SBAR — плановая коммуникация';
    if (urg === 'urgent') { color = '#F59E0B'; band = 'SBAR — срочная коммуникация'; }
    if (urg === 'emergent') { color = '#EF4444'; band = 'SBAR — экстренная коммуникация'; }

    return {
      value: 'SBAR',
      unit: 'шаблон',
      interpretation: band,
      color,
      details: `S — Situation: ${t.s}\n\nB — Background: ${t.b}\n\nA — Assessment: ${t.a}\n\nR — Recommendation: ${t.r}`,
      actions: [
        'Прежде чем звонить: проверить ЭМК, свежие витальные, анализы, назначения',
        'Записать ключевые цифры (ЧСС, АД, SpO2, Hb, лактат) перед звонком',
        'Использовать read-back (собеседник повторяет ключевые назначения)',
        urg === 'emergent' ? 'Параллельно начать ABCDE/ALS — не ждать консультанта' : '',
        'Документировать разговор в ЭМК: время, собеседник, ключевые рекомендации',
        'При несогласии — эскалировать по цепочке (chain of command)',
      ].filter(Boolean),
      caveats: [
        'SBAR — инструмент коммуникации, не замена клинического решения',
        'Разработан ВМФ США, адаптирован для здравоохранения Kaiser Permanente (2002)',
        'Рекомендован Joint Commission, WHO, NHS для снижения communication errors',
        'Альтернативы: ISBAR (I = Identify), I-PASS (педиатрия), SHARED (NHS)',
        'Read-back обязателен при вербальных назначениях препаратов (Joint Commission NPSG)',
      ],
      related: [
        { id: 'nrs-2002', title: 'NRS-2002' },
        { id: 'news2', title: 'NEWS2' },
      ],
      relatedCourses: [
        { id: '901.1', title: 'Клиническая коммуникация' },
        { id: '902.1', title: 'Пациентская безопасность' },
      ],
    };
  },
  reference: 'Haig KM, Sutton S, Whittington J. SBAR: a shared mental model for improving communication between clinicians. Jt Comm J Qual Patient Saf. 2006;32(3):167-175.',
  countries: 'Международный (IHI / Joint Commission)',
  presets: [
    { label: 'Ухудшение — экстренно', values: { scenario: 'deterioration', urgency: 'emergent' } },
    { label: 'Передача смены', values: { scenario: 'handover', urgency: 'routine' } },
    { label: 'Телефонная консультация', values: { scenario: 'consult', urgency: 'urgent' } },
  ],
  info: `### Для чего используется
**SBAR** — стандартизированный формат коммуникации между медработниками для сокращения ошибок и улучшения передачи критической информации.

### Структура
| Буква | Содержание |
|---|---|
| **S** — Situation | Что происходит сейчас, пациент, палата, основная жалоба |
| **B** — Background | Контекст: диагноз, анамнез, текущая терапия, аллергия |
| **A** — Assessment | Ваша оценка / дифф. диагноз / что беспокоит |
| **R** — Recommendation | Конкретный запрос: что и когда нужно сделать |

### Когда применять
- Ухудшение состояния пациента (rapid response)
- Передача смены (shift handover)
- Звонок консультанту / специалисту
- Медсестра → врач
- Перевод между отделениями
- Выписка и передача в амбулаторию

### Эффективность
- Снижение нежелательных событий на 30-50% (Kaiser, VA)
- Улучшение восприятия командной работы
- Требует обучения и практики (аудиотренажёры)

### Read-back
Собеседник **повторяет вслух** критические назначения (доза, препарат, время) — обязательно при вербальных указаниях (Joint Commission NPSG).

### Варианты
- **ISBAR** — +I (Identify): представление говорящего
- **I-PASS** — Illness severity, Patient summary, Action list, Situation awareness, Synthesis (педиатрия)
- **SHARED** (NHS) — Situation, History, Assessment, Recommendation, Evaluation, Decision

### Применение в командной работе
- Crew Resource Management (CRM)
- Briefings / debriefings
- TeamSTEPPS (AHRQ)

### Источник
Haig KM et al. Jt Comm J Qual Patient Saf 2006;32:167.`,
};

export default runner;
