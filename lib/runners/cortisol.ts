// @ts-nocheck
/** Runner: cortisol - Cortisol screening (AI/Cushing) */
import type {
  CalculatorTool, ToolInput, Preset, CalculatorResult, ResultExtras, ResultScaleSegment,
} from '../tools-runners';

const runner: CalculatorTool = {
  kind: 'calculator',
  inputs: [
    { id: 'test', label: 'Тип теста', type: 'select', options: [
      { value: 'am', label: 'Утренний кортизол (8:00) - скрининг надпочечниковой недостаточности' },
      { value: 'dst', label: '1 mg dexamethasone suppression (DST, 23:00) - скрининг Cushing' },
      { value: 'midnight', label: 'Ночная слюна/сыворотка (23:00) - скрининг Cushing' },
      { value: 'uff', label: '24 ч свободный кортизол мочи (UFC)' },
    ] },
    { id: 'cortisol', label: 'Кортизол', type: 'number', unit: 'нмоль/л или нмоль/сут', min: 0, max: 3000, step: 1, quickValues: [50, 150, 300, 500, 1000] },
    { id: 'acth', label: 'АКТГ (опционально)', type: 'number', unit: 'пг/мл', min: 0, max: 2000, step: 1, quickValues: [0, 15, 50, 100, 300] },
  ],
  compute: (v) => {
    const test = String(v.test);
    const c = Number(v.cortisol);
    const acth = Number(v.acth);

    let band = '', color = '#22C55E', details = '', actions = [];

    if (test === 'am') {
      // Morning cortisol 8 AM (серум, нмоль/л)
      if (c < 100) {
        band = 'АН исключать срочно'; color = '#EF4444';
        details = `Утренний кортизол ${c} нмоль/л (< 100) - высокая вероятность надпочечниковой недостаточности.`;
        actions = [
          'Тест стимуляции ACTH (250 мкг тетракозактид в/в, кортизол через 30 и 60 мин - норма > 500 нмоль/л)',
          'Гидрокортизон 100 мг в/в немедленно при клинике (не ждать теста)',
          'АКТГ: высокий → первичная (Аддисон); низкий/норм → вторичная/третичная',
          'Анти-адренальные антитела, электролиты, глюкоза',
        ];
      } else if (c < 500) {
        band = 'Неопределённо'; color = '#F59E0B';
        details = `Утренний кортизол ${c} нмоль/л - серая зона. Требуется стимуляционный тест.`;
        actions = ['ACTH-стимуляционный тест (тетракозактид 250 мкг в/в)', 'Инсулиновая гипогликемия (при сохранной системе)', 'Метирапоновый тест (гипофизарный резерв)'];
      } else {
        band = 'Надпочечники OK'; color = '#22C55E';
        details = `Утренний кортизол ${c} нмоль/л (> 500) - надпочечниковая недостаточность маловероятна.`;
        actions = ['При типичной клинике - стимуляционный тест для подтверждения', 'Оценить иные причины гипотензии/слабости'];
      }
    } else if (test === 'dst') {
      // 1 mg DST overnight - norm < 50 nmol/L (< 1.8 µg/dL)
      if (c < 50) {
        band = 'Cushing исключён'; color = '#22C55E';
        details = `Кортизол после 1 мг DST ${c} нмоль/л (< 50 / < 1.8 мкг/дл) - адекватная супрессия, Cushing маловероятен.`;
        actions = ['Повторить при стойкой клинике через 3-6 мес', 'Искать иные причины (ятрогенный стероид, ожирение, депрессия)'];
      } else if (c < 138) {
        band = 'Подозрит. на Cushing'; color = '#F59E0B';
        details = `Кортизол ${c} нмоль/л после DST (50-138) - неполная супрессия. Требуется подтверждение.`;
        actions = ['Повторить DST + ночная слюна / 24 ч моча UFC', 'Исключить псевдо-Cushing (алкоголь, депрессия, ожирение)', 'CRH-тест, 2 мг DST × 48 ч (малый), dexa-CRH'];
      } else {
        band = 'Cushing вероятен'; color = '#EF4444';
        details = `Кортизол ${c} нмоль/л после 1 мг DST - отсутствие супрессии. Синдром Cushing вероятен.`;
        actions = [
          'Подтвердить 2-м тестом (UFC или ночная слюна)',
          'АКТГ: ↓ (< 10 пг/мл) → АКТГ-независимый (надпочечник), КТ надпочечников',
          'АКТГ ↑ → АКТГ-зависимый (гипофиз 80% / эктопия 20%), МРТ гипофиза + 8 мг DST + IPSS',
          'Консультация эндокринолога',
        ];
      }
    } else if (test === 'midnight') {
      // Midnight salivary/serum cortisol - norm < 4 nmol/L saliva or < 200 nmol/L serum
      if (c < 4) {
        band = 'Норма (слюна)'; color = '#22C55E';
        details = `Ночная слюна ${c} нмоль/л (< 4) - нормальный циркадный ритм.`;
        actions = ['Cushing маловероятен, искать иные причины'];
      } else if (c < 10) {
        band = 'Пограничное'; color = '#F59E0B';
        details = `Ночной кортизол слюны ${c} нмоль/л - пограничное значение, повторить.`;
        actions = ['Повторить 2-3 раза в течение недели', 'DST как дополнительный тест', 'Исключить депрессию, алкоголь, ХПН'];
      } else {
        band = 'Ритм нарушен'; color = '#EF4444';
        details = `Ночной кортизол слюны ${c} нмоль/л (> 10) - потеря циркадного ритма. Cushing вероятен.`;
        actions = ['Подтвердить DST или UFC', 'АКТГ, МРТ гипофиза или КТ надпочечников'];
      }
    } else {
      // UFC 24h - norm < 138 nmol/day (approx < 50 µg/day)
      if (c < 138) {
        band = 'UFC норма'; color = '#22C55E';
        details = `24 ч UFC ${c} нмоль/сут - в норме, Cushing маловероятен.`;
        actions = ['Повторить при стойкой клинике', 'Искать иные причины'];
      } else if (c < 414) {
        band = 'UFC повышен'; color = '#F59E0B';
        details = `24 ч UFC ${c} нмоль/сут (1-3 × ВГН) - требуется подтверждение.`;
        actions = ['Повторить UFC 2-3 раза', 'DST или ночная слюна', 'Исключить ложно-положительные (стресс, депрессия, полиурия)'];
      } else {
        band = 'UFC высокий'; color = '#EF4444';
        details = `24 ч UFC ${c} нмоль/сут (> 3 × ВГН) - Cushing высоко вероятен.`;
        actions = ['АКТГ для дифференциации этиологии', 'МРТ гипофиза или КТ надпочечников', 'Эндокринолог'];
      }
    }

    // ACTH interpretation add-on
    const acthInterp = acth > 0
      ? acth > 60
        ? ' АКТГ повышен (>60) - АКТГ-зависимый Cushing (гипофиз/эктопия) или надпочечниковая недостаточность первичная.'
        : acth < 10
          ? ' АКТГ подавлен (<10) - АКТГ-независимый Cushing (опухоль надпочечника) или вторичная/третичная АН.'
          : ' АКТГ в норме.'
      : '';

    return {
      value: c.toFixed(0), unit: test === 'uff' ? 'нмоль/сут' : 'нмоль/л',
      interpretation: band, color,
      details: details + acthInterp, actions,
      caveats: [
        'Утренний кортизол варьирует 200-700 нмоль/л, имеет циркадный ритм',
        '1 mg DST: норма < 50 нмоль/л (Endocrine Society, 2008)',
        'Ночная слюна: 2-3 измерения, норма < 4 нмоль/л',
        '24 ч UFC: верхняя граница ~138 нмоль/сут, повторить ≥ 2 раза',
        'Ложно-положительные DST: индукторы CYP3A4 (фенитоин, рифампин) ускоряют метаболизм декс.',
      ],
      scale: {
        segments: [
          { min: 0, max: test === 'dst' ? 50 : test === 'midnight' ? 4 : test === 'uff' ? 138 : 100, label: 'Норма', color: '#22C55E' },
          { min: test === 'dst' ? 50 : test === 'midnight' ? 4 : test === 'uff' ? 138 : 100, max: test === 'dst' ? 138 : test === 'midnight' ? 10 : test === 'uff' ? 414 : 500, label: 'Погран.', color: '#F59E0B' },
          { min: test === 'dst' ? 138 : test === 'midnight' ? 10 : test === 'uff' ? 414 : 500, max: test === 'uff' ? 2000 : 1500, label: 'Патология', color: '#EF4444' },
        ],
        current: Math.min(c, test === 'uff' ? 2000 : 1500),
        unit: test === 'uff' ? 'нмоль/сут' : 'нмоль/л',
      },
      related: [
        { id: 'tsh', title: 'TSH панель' },
        { id: 'arr', title: 'ARR (альдостерон)' },
      ],
      relatedCourses: [
        { id: '308.1', title: 'Эндокринология' },
        { id: '308.2', title: 'Надпочечники' },
      ],
    };
  },
  reference: 'Nieman LK et al. The Diagnosis of Cushing\'s Syndrome. J Clin Endocrinol Metab 2008;93:1526.',
  countries: 'Международный (Endocrine Society · РАЭ)',
  presets: [
    { label: 'Утренний 80 (АН)', values: { test: 'am', cortisol: 80, acth: 150 } },
    { label: 'DST 30 (норма)', values: { test: 'dst', cortisol: 30, acth: 0 } },
    { label: 'DST 200 (Cushing)', values: { test: 'dst', cortisol: 200, acth: 80 } },
  ],
  info: `### Для чего используется
Скрининг гиперкортицизма (синдром Cushing) и надпочечниковой недостаточности.

### Тесты первой линии при подозрении на Cushing (≥ 2 положительных)
| Тест | Норма | Cushing |
|---|---|---|
| 1 mg DST overnight | < 50 нмоль/л | > 50 |
| Ночная слюна × 2 | < 4 нмоль/л | > 10 |
| 24 ч UFC × 2 | < 138 нмоль/сут | > 414 (3× ВГН) |

### Надпочечниковая недостаточность
| Утренний кортизол | Тактика |
|---|---|
| < 100 нмоль/л | Высокая вероятность АН - стимтест + экстренно ГКС |
| 100-500 | Серая зона - стимтест (250 мкг тетракозактид) |
| > 500 | АН маловероятна |

### АКТГ дифф.диагноз
| АКТГ | Интерпретация |
|---|---|
| ↑ + кортизол ↑ | АКТГ-зависимый Cushing (гипофиз / эктопия) |
| ↓ + кортизол ↑ | АКТГ-независимый (опухоль надпочечника) |
| ↑ + кортизол ↓ | Первичная АН (болезнь Аддисона) |
| ↓ + кортизол ↓ | Вторичная / третичная АН (гипофиз / гипоталамус) |

### Источник
Nieman LK et al. Endocrine Society CPG. J Clin Endocrinol Metab 2008;93:1526.`,
};

export default runner;
