/** Runner: who-ladder */
import type {
  CalculatorTool, ToolInput, ScoreBand, Preset,
  CalculatorResult, ResultExtras, ResultScaleSegment,
} from '../tools-runners';

const runner: CalculatorTool = {
  kind: 'calculator',
  inputs: [
    {
      id: 'intensity',
      label: 'Интенсивность боли (NRS 0-10)',
      type: 'select',
      options: [
        { value: 'mild', label: 'Лёгкая (1-3)' },
        { value: 'moderate', label: 'Умеренная (4-6)' },
        { value: 'severe', label: 'Сильная (7-10)' },
        { value: 'breakthrough', label: 'Прорывная боль (эпизодическая)' },
      ],
    },
    {
      id: 'neuropathic',
      label: 'Нейропатический компонент (жжение, стреляющая, парестезии)',
      type: 'checkbox',
    },
    {
      id: 'naive',
      label: 'Опиоид-наивный (не получал сильных опиоидов)',
      type: 'checkbox',
    },
    {
      id: 'renal',
      label: 'Почечная недостаточность (eGFR < 30)',
      type: 'checkbox',
    },
  ],
  compute: (v) => {
    const intensity = String(v.intensity);
    const neuro = !!v.neuropathic;
    const naive = !!v.naive;
    const renal = !!v.renal;

    let step = 1;
    let color = '#22C55E';
    let drug = '';
    let dose = '';
    let adj = '';

    if (intensity === 'mild') {
      step = 1;
      color = '#22C55E';
      drug = 'Парацетамол и/или НПВС';
      dose = 'Парацетамол 500-1000 мг × 4/сут (макс 4 г) или ибупрофен 400 мг × 3-4 / напроксен 500 мг × 2';
    } else if (intensity === 'moderate') {
      step = 2;
      color = '#F59E0B';
      drug = 'Слабый опиоид ± парацетамол';
      dose = 'Трамадол 50-100 мг × 3-4/сут (макс 400 мг) или кодеин 30-60 мг × 4 + парацетамол 500 мг';
      adj = 'Добавить парацетамол 500-1000 мг × 4';
    } else if (intensity === 'severe') {
      step = 3;
      color = '#EF4444';
      if (naive) {
        drug = 'Сильный опиоид (старт)';
        dose = 'Морфин ПО 5-10 мг × 4-6/сут (при eGFR > 30). Оксикодон 5 мг × 4-6. Титровать по ответу.';
      } else {
        drug = 'Сильный опиоид (ротация/титрование)';
        dose = 'Морфин ПО 10-30 мг × 4-6 или SR 30-60 мг × 2; фентанил ТТС 12-25 мкг/ч при стабильной боли';
      }
      if (renal) {
        drug = 'Сильный опиоид (почечная недост.)';
        dose = 'Фентанил ТТС или метадон (нет почечного метаболизма); ИЗБЕГАТЬ морфина и кодеина';
      }
    } else {
      step = 3;
      color = '#7F1D1D';
      drug = 'Прорывная боль (break­through)';
      dose = '10-15% от суточной дозы ПО опиоида; фентанил буккальный / интраназальный при быстром начале';
    }

    const adjuvant = neuro
      ? 'Габапентин 100-300 мг на ночь → 300 × 3 (макс 3600) или прегабалин 75 × 2 (макс 600); амитриптилин 10-25 мг на ночь; дексаметазон при компрессии'
      : '';

    return {
      value: `Шаг ${step}`,
      unit: 'лестница ВОЗ',
      interpretation: `Шаг ${step} — ${drug}. ${intensity === 'breakthrough' ? 'Прорывная боль — rescue доза.' : ''}`,
      color,
      details: `${drug}. Режим: ${dose}. ${adj}`,
      actions: [
        dose,
        adj,
        adjuvant ? `Нейропатический адъювант: ${adjuvant}` : '',
        step === 3 ? 'Слабительное (лактулоза, сенна, макрогол) для ПРОФИЛАКТИКИ запора — обязательно при опиоидах' : '',
        step === 3 ? 'Ондансетрон 4 мг или метоклопрамид 10 мг для профилактики тошноты (первые 5-7 дн)' : '',
        step === 3 ? 'Rescue доза: 10-15% суточной дозы опиоида при прорывной боли' : '',
        'Переоценка через 24-72 ч; титровать по ответу и побочным эффектам',
        'Избегать меперидин (петидин) в длительном применении — нейротоксичность норметаболита',
      ].filter(Boolean),
      caveats: [
        'WHO Analgesic Ladder (1986, обновлён 2018) — стандарт для онкологической боли',
        'Шаг 2 (слабые опиоиды) — спорный; многие гайды переходят сразу на шаг 3 с низких доз',
        'Морфин — препарат выбора (WHO essential medicine); противопоказан при eGFR < 30',
        'Фентанил ТТС применять только при СТАБИЛЬНОЙ боли (начало действия 12-24 ч)',
        'Метадон — сложная фармакокинетика, требует опыта (длинный T1/2, QT ↑)',
        'Нейропатическая боль часто не отвечает только на опиоиды — адъюванты обязательны',
        'Индивидуальный подход: возраст, почки, печень, когнитивный статус',
      ],
      scale: {
        segments: [
          { min: 1, max: 2, label: 'Шаг 1', color: '#22C55E' },
          { min: 2, max: 3, label: 'Шаг 2', color: '#F59E0B' },
          { min: 3, max: 4, label: 'Шаг 3', color: '#EF4444' },
        ],
        current: step,
        unit: 'шаг',
      },
      related: [
        { id: 'pps', title: 'PPS' },
        { id: 'phq9', title: 'PHQ-9' },
        { id: 'gcs', title: 'GCS' },
      ],
      relatedCourses: [
        { id: '309.3', title: 'Паллиативная помощь' },
        { id: '309.2', title: 'Клиническая онкология' },
      ],
    };
  },
  reference: 'WHO. Cancer Pain Relief, 2nd ed. Geneva: WHO; 1996. + WHO Guidelines for the Pharmacological and Radiotherapeutic Management of Cancer Pain in Adults and Adolescents. Geneva: WHO; 2018.',
  countries: 'Международный (ВОЗ, ESMO, NCCN, IASP)',
  presets: [
    { label: 'Лёгкая', values: { intensity: 'mild', neuropathic: false, naive: true, renal: false } },
    { label: 'Умеренная', values: { intensity: 'moderate', neuropathic: false, naive: true, renal: false } },
    { label: 'Сильная нейроп.', values: { intensity: 'severe', neuropathic: true, naive: true, renal: false } },
  ],
  info: `### Для чего используется
**WHO Analgesic Ladder (Лестница ВОЗ, 1986, обновлена 2018)** — ступенчатая схема обезболивания онкологической боли.

### Шаги
| Шаг | Интенсивность | Препараты |
|---|---|---|
| **1** | Лёгкая (1-3) | Парацетамол, НПВС |
| **2** | Умеренная (4-6) | Слабые опиоиды (трамадол, кодеин) ± парацетамол |
| **3** | Сильная (7-10) | Сильные опиоиды (морфин, оксикодон, фентанил, гидроморфон) |
| + | Прорывная | Rescue 10-15% суточной дозы |

### Адъюванты (на любом шаге)
- **Нейропатическая боль**: габапентин, прегабалин, амитриптилин, дулоксетин
- **Костная боль**: бисфосфонаты (золедроновая к-та), деносумаб, ЛТ
- **Компрессия**: дексаметазон 8-16 мг/сут
- **Спазмы**: баклофен, тизанидин
- **Тревога**: бензодиазепины (осторожно)

### Сильные опиоиды — стартовые дозы (опиоид-наивный)
| Препарат | Путь | Доза | Особенности |
|---|---|---|---|
| **Морфин** | ПО | 5-10 мг × 4-6 | Стандарт ВОЗ; НЕ при eGFR < 30 |
| **Оксикодон** | ПО | 5 мг × 4-6 | Меньше галлюцинаций |
| **Гидроморфон** | ПО | 1-2 мг × 4 | Безопасен при почечной недост. |
| **Фентанил** | ТТС | 12-25 мкг/ч | Только при стабильной боли |
| **Метадон** | ПО | 2.5-5 мг × 2-3 | Для экспертов; QT ↑ |

### Эквианальгетические дозы (ПО)
- Морфин 30 мг = оксикодон 20 мг = гидроморфон 7.5 мг = фентанил ТТС 12 мкг/ч

### Ротация опиоидов
- При неэффективности / токсичности
- Снизить дозу на **25-50%** при ротации (incomplete cross-tolerance)

### Побочные эффекты опиоидов
| Симптом | Тактика |
|---|---|
| Запор | Лактулоза/сенна/макрогол ПРОФИЛАКТИЧЕСКИ; налоксегол/метилналтрексон при резист. |
| Тошнота | Метоклопрамид 10 мг / ондансетрон 4 мг (первые 5-7 дн) |
| Седация | Снизить дозу / ротация; метилфенидат |
| Угнетение дыхания | Налоксон 0.04-0.4 мг IV титровать |
| Гиперальгезия | Ротация на метадон |

### Прорывная боль (breakthrough)
- **Rescue доза = 10-15% суточной ПО дозы опиоида**
- Быстрое начало: фентанил буккальный / интраназальный / сублингвальный
- Если > 4 rescue/сутки → увеличить базовую дозу

### Интервенционные методы (шаг 4)
- Эпидуральная / интратекальная анальгезия
- Блокада чревного сплетения (рак поджелудочной)
- Спинальный нейролиз

### Ограничения
- Критика шага 2 — многие гайды (ESMO, NCCN) рекомендуют переход сразу на шаг 3 с низких доз
- Фиксированные дозы ± «по требованию» обычно менее эффективны, чем регулярные
- Нейропатическая боль часто не купируется только опиоидами`,
};
export default runner;
