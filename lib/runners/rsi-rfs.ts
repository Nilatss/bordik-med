/** Runner: rsi-rfs - Reflux Symptom Index + Reflux Finding Score for LPR */
import type { CalculatorTool } from '../tools-runners';

const runner: CalculatorTool = {
  kind: 'calculator',
  inputs: [
    {
      id: 'rsi',
      label: 'RSI (Reflux Symptom Index): 9 симптомов × 0-5, сумма 0-45',
      type: 'number',
      min: 0,
      max: 45,
      step: 1,
      quickValues: [5, 13, 20, 30],
      hint: 'Охриплость, прочистка горла, слизь, затруднение глотания, кашель после еды/лёжа, удушье, хрон. кашель, ком в горле, изжога/ГЭРБ',
    },
    {
      id: 'rfs',
      label: 'RFS (Reflux Finding Score): 8 эндоскопических находок × 0-4, сумма 0-26',
      type: 'number',
      min: 0,
      max: 26,
      step: 1,
      quickValues: [3, 7, 12, 18],
      hint: 'Субглоттич. отёк, отёк желудочков, гиперемия гортани, отёк голос. складок, диффузный отёк, гипертрофия задней комиссуры, гранулёма/гранулирование, густая эндоларингеальная слизь',
    },
  ],
  compute: (v) => {
    const rsi = Math.min(45, Number(v.rsi) || 0);
    const rfs = Math.min(26, Number(v.rfs) || 0);
    const rsiPos = rsi > 13;
    const rfsPos = rfs > 7;

    let diagnosis = '';
    let color = '#22C55E';
    let details = '';

    if (rsiPos && rfsPos) {
      diagnosis = 'Ларингофарингеальный рефлюкс (ЛФР)';
      color = '#EF4444';
      details = `RSI ${rsi} (> 13) + RFS ${rfs} (> 7) - оба позитивных. Высокая вероятность ЛФР.`;
    } else if (rsiPos || rfsPos) {
      diagnosis = 'Подозрение на ЛФР';
      color = '#F59E0B';
      details = `Только ${rsiPos ? 'RSI' : 'RFS'} позитивный (RSI ${rsi}, RFS ${rfs}). Чувствительность повышается при обоих > порога.`;
    } else {
      diagnosis = 'ЛФР маловероятен';
      color = '#22C55E';
      details = `RSI ${rsi} (≤ 13) + RFS ${rfs} (≤ 7) - оба в пределах нормы.`;
    }

    return {
      value: `RSI ${rsi} / RFS ${rfs}`,
      interpretation: diagnosis,
      color,
      details,
      actions: [
        rsiPos || rfsPos ? 'PPI × 2 раза/день × 8-12 недель (эмпирическая терапия)' : 'Без специфической терапии',
        'Режим: не есть за 3 ч до сна, приподнятое изголовье, снижение веса',
        'Избегать кофе, шоколада, алкоголя, острого, томатов',
        rfs >= 12 ? 'Гастроэнтеролог + ФГДС + pH-импедансометрия 24 ч (dual-probe)' : '',
        'Повтор RSI через 2-3 месяца; при снижении ≥ 5 баллов - ответ на терапию',
        'При рефрактерности: алгинаты (Gaviscon), H2-блокаторы на ночь, баклофен',
        'Fundoplication при рефрактерной ГЭРБ с подтверждённым pH-мониторингом',
      ].filter(Boolean),
      caveats: [
        'RSI > 13 и RFS > 7 (Belafsky 2001, 2002) - скрининг, не диагноз',
        'Специфичность низкая (~30-40 %): симптомы перекрываются с хр. ларингитом курильщика, аллергией, функц. ларингоспазмом',
        'Золотой стандарт: 24-ч pH-импедансометрия с dual probe (фарингеальный)',
        'Чувствительность эмпирического PPI не идеальна - 50-70 % пациентов отвечают',
        'Альтернативы: RESQ-7, DS-LPRD, PepTest (пепсин в слюне, коммерч.)',
        'У детей: PRSI (Pediatric RSI, Karkos 2011)',
      ],
      scale: {
        segments: [
          { min: 0, max: 13, label: 'RSI норма', color: '#22C55E' },
          { min: 14, max: 45, label: 'RSI ↑', color: '#EF4444' },
        ],
        current: rsi,
        unit: 'RSI',
      },
      related: [
        { id: 'vhi', title: 'VHI' },
        { id: 'snot22', title: 'SNOT-22' },
      ],
      relatedCourses: [{ id: '314.3', title: 'Оториноларингология' }],
    };
  },
  reference: 'Belafsky PC, Postma GN, Koufman JA. RSI: Validity and reliability. J Voice 2002;16:274-7. RFS: Laryngoscope 2001;111:1313-7.',
  countries: 'Международный (AAO-HNS)',
  presets: [
    { label: 'Вероятный ЛФР', values: { rsi: 22, rfs: 12 } },
    { label: 'Только симптомы', values: { rsi: 18, rfs: 5 } },
    { label: 'Норма', values: { rsi: 8, rfs: 4 } },
  ],
  info: `### Для чего используется
**RSI + RFS** (Belafsky 2001-2002) - скрининговые инструменты **ларингофарингеального рефлюкса (ЛФР / LPR)**.

### RSI - Reflux Symptom Index (самоотчёт)
9 симптомов × 0-5 (0 = нет, 5 = тяжело), итого **0-45**:
1. Охриплость
2. Прочистка горла
3. Избыток слизи / postnasal drip
4. Затруднённое глотание
5. Кашель после еды / лёжа
6. Удушье / затруднённое дыхание
7. Хронический кашель
8. Ком в горле (globus)
9. Изжога / кислая отрыжка

**Cutoff: > 13** = вероятный ЛФР.

### RFS - Reflux Finding Score (эндоскопически)
8 находок × 0-2 или 0-4, итого **0-26**:
1. Субглоттический отёк (псевдосулькус) - 0/2
2. Отёк желудочков (ventricular obliteration) - 0/2/4
3. Гиперемия / эритема - 0/2/4
4. Отёк голосовых складок - 0/1/2/3/4
5. Диффузный ларингеальный отёк - 0/1/2/3/4
6. Гипертрофия задней комиссуры - 0/1/2/3/4
7. Гранулёма / грануляции - 0/2
8. Густая эндоларингеальная слизь - 0/2

**Cutoff: > 7** = вероятный ЛФР.

### Интерпретация
| RSI | RFS | Диагноз |
|---|---|---|
| > 13 | > 7 | Вероятный ЛФР |
| > 13 или > 7 | Подозрение |
| ≤ 13 и ≤ 7 | ЛФР маловероятен |

### Терапевтический подход
1. **PPI × 2/день × 8-12 нед** (омепразол 20 мг, эзомепразол 40 мг)
2. **Lifestyle**: без еды за 3 ч до сна, приподнятое изголовье 15°, снижение веса
3. **Алгинаты** (Gaviscon Advance) - после еды
4. При рефрактерности: **pH-импедансометрия 24 ч с двойным зондом**
5. Хирургия (fundoplication) - редко

### Ограничения
- Низкая специфичность (30-40 %) - перекрытие с хр. ларингитом, аллергией, курением
- **Золотой стандарт диагностики**: 24-ч pH-импедансометрия dual-probe
- 50-70 % эмпирический ответ на PPI

### Источник
Belafsky PC et al. J Voice 2002;16:274 (RSI); Laryngoscope 2001;111:1313 (RFS).`,
};

export default runner;
