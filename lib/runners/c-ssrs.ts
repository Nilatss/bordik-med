// @ts-nocheck
/** Runner: c-ssrs — Columbia Suicide Severity Rating Scale */
import type {
  CalculatorTool,
  ToolInput,
  Preset,
} from '../tools-runners';

const runner: CalculatorTool = {
  kind: 'calculator',
  countries: 'США · ЕС · РФ · FDA стандарт',
  reference:
    'Posner K, Brown GK, Stanley B, et al. The Columbia-Suicide Severity Rating Scale: Initial validity and internal consistency findings. Am J Psychiatry. 2011;168:1266-1277.',
  inputs: [
    {
      id: 'category',
      label: 'Высшая категория суицидальной идеации/поведения',
      type: 'select',
      options: [
        { value: '0', label: '0. Отсутствие суицидальных мыслей' },
        { value: '1', label: '1. Желание быть мёртвым (пассивное)' },
        { value: '2', label: '2. Неспецифические активные суицидальные мысли' },
        { value: '3', label: '3. Суицидальные мысли с методом (без намерения, без плана)' },
        { value: '4', label: '4. Суицидальные мысли с намерением (без плана)' },
        { value: '5', label: '5. Суицидальные мысли с планом и намерением' },
      ],
    },
    {
      id: 'attempt_lifetime',
      label: 'Суицидальная попытка когда-либо в жизни',
      type: 'checkbox',
      points: 0,
    },
    {
      id: 'attempt_3m',
      label: 'Суицидальная попытка / подготовка / прерванная попытка в последние 3 мес',
      type: 'checkbox',
      points: 0,
    },
    {
      id: 'nssi',
      label: 'Несуицидальное самоповреждение',
      type: 'checkbox',
      points: 0,
    },
  ],
  presets: [
    { label: 'Низкий (1)', values: { category: '1', attempt_lifetime: false, attempt_3m: false, nssi: false } },
    { label: 'Средний (3)', values: { category: '3', attempt_lifetime: true, attempt_3m: false, nssi: false } },
    { label: 'Высокий (5 + попытка)', values: { category: '5', attempt_lifetime: true, attempt_3m: true, nssi: false } },
  ],
  compute: (v) => {
    const cat = Number(v.category) || 0;
    const lifetime = v.attempt_lifetime === true;
    const recent = v.attempt_3m === true;
    const nssi = v.nssi === true;

    let color = '#22C55E';
    let label = 'Без суицидального риска';
    let details = 'Нет текущих суицидальных мыслей или поведения.';
    const actions: string[] = [];
    let risk: 'none' | 'low' | 'moderate' | 'high' = 'none';

    if (cat >= 4 || recent) {
      risk = 'high';
      color = '#7F1D1D';
      label = 'Высокий риск';
      details = cat >= 5
        ? 'Суицидальные мысли с планом И намерением — категория 5 C-SSRS. Высочайший риск.'
        : recent
          ? 'Суицидальное поведение в последние 3 мес (попытка, подготовка, прерванная попытка) — высокий риск.'
          : 'Суицидальные мысли с намерением — категория 4. Высокий риск.';
      actions.push(
        '⚠️ НЕМЕДЛЕННАЯ психиатрическая оценка',
        'Госпитализация (добровольная или недобровольная при отказе)',
        'Убрать средства (оружие, лекарства) — means restriction',
        'Постоянное наблюдение до передачи специалисту',
        'Safety plan (Stanley-Brown), контакты кризисной линии',
      );
    } else if (cat === 3 || lifetime) {
      risk = 'moderate';
      color = '#EF4444';
      label = 'Средний риск';
      details = cat === 3
        ? 'Активные суицидальные мысли с методом, но без плана и намерения — категория 3.'
        : 'Суицидальная попытка в анамнезе (когда-либо) — пожизненно повышенный риск, даже без текущих мыслей.';
      actions.push(
        'Срочная (в течение 24 ч) оценка психиатра',
        'Safety plan + means restriction',
        'Активизация социальной поддержки',
        'Рассмотреть стационарное или интенсивное амбулаторное лечение',
        'Лечение основной психиатрической патологии (депрессия, биполяр, ПРЛ)',
      );
    } else if (cat === 2) {
      risk = 'low';
      color = '#F59E0B';
      label = 'Низкий-умеренный риск';
      details = 'Неспецифические активные суицидальные мысли ("хочу умереть", "не хочу жить") без метода — категория 2.';
      actions.push(
        'Психиатрическая оценка в ближайшие дни',
        'Лечение основной патологии (антидепрессанты при депрессии)',
        'Safety plan, семейная поддержка',
        'Контрольный визит через 1 нед',
      );
    } else if (cat === 1) {
      risk = 'low';
      color = '#FACC15';
      label = 'Низкий риск';
      details = 'Пассивное желание быть мёртвым без активных мыслей о действии.';
      actions.push(
        'Психиатрическая / психологическая оценка',
        'Лечение основной патологии',
        'Психообразование, контактный телефон кризисной линии',
      );
    } else {
      actions.push('Повторный скрининг при появлении депрессии, значимых жизненных событий');
    }

    if (nssi) {
      actions.push('Несуицидальное самоповреждение — фактор риска будущего суицида; ДБТ при ПРЛ');
    }
    if (lifetime && risk !== 'high') {
      actions.push('Анамнез попытки — сильнейший предиктор будущего суицида (пожизненный мониторинг)');
    }

    return {
      value: `Кат. ${cat}`,
      unit: 'C-SSRS',
      color,
      interpretation: label,
      details,
      actions,
      caveats: [
        'C-SSRS — стандарт FDA для оценки суицидальности в клинических исследованиях',
        'Интерпретация по высшей достигнутой категории идеации + наличию поведения',
        'Попытка в анамнезе — сильнейший единичный предиктор; риск сохраняется пожизненно',
        'Активные мысли С планом И намерением — ВСЕГДА высокий риск → немедленная интервенция',
        'Documented risk assessment — обязательно в медицинской документации',
      ],
      scale: {
        segments: [
          { min: 0, max: 0, label: '0 нет', color: '#22C55E' },
          { min: 1, max: 1, label: '1 пассивное', color: '#FACC15' },
          { min: 2, max: 2, label: '2 активное', color: '#F59E0B' },
          { min: 3, max: 3, label: '3 метод', color: '#EF4444' },
          { min: 4, max: 4, label: '4 намерение', color: '#DC2626' },
          { min: 5, max: 5, label: '5 план', color: '#7F1D1D' },
        ],
        current: cat,
        unit: 'категория',
      },
      related: [
        { id: 'beck-ssi', title: 'Beck SSI' },
        { id: 'phq9', title: 'PHQ-9 (пункт 9)' },
        { id: 'bdi', title: 'BDI-II' },
      ],
      relatedCourses: [{ id: '201.3', title: 'Нейрофизиология' }],
    };
  },
  info: `### Для чего используется
**Columbia-Suicide Severity Rating Scale (C-SSRS, Posner 2011)** — стандарт FDA для оценки суицидальной идеации и поведения. Рекомендована для обязательного скрининга в психиатрии, скорой помощи, первичной помощи.

### Иерархия идеации (оценивается по ВЫСШЕЙ достигнутой категории)
| Кат. | Идеация | Риск |
|---|---|---|
| 1 | Желание быть мёртвым (пассивное) | Низкий |
| 2 | Неспецифические активные суицидальные мысли | Низкий-умеренный |
| 3 | Суицидальные мысли С методом (без намерения, без плана) | Средний |
| 4 | Суицидальные мысли С намерением (без плана) | Высокий |
| 5 | Суицидальные мысли С ПЛАНОМ И НАМЕРЕНИЕМ | Высочайший |

### Суицидальное поведение
- **Actual attempt** — совершённая попытка
- **Interrupted attempt** — прерванная попытка (что-то остановило до действия)
- **Aborted attempt** — прекращённая самим человеком
- **Preparatory acts** — подготовка (покупка оружия, написание записки, сбор лекарств)
- **NSSI** — несуицидальное самоповреждение (без намерения умереть)

### Ключевые предикторы высокого риска
1. Суицидальные мысли с планом И намерением (cat 5)
2. Попытка, прерванная попытка, подготовка в последние 3 мес
3. Пожизненный анамнез попытки
4. Безнадёжность (BDI пункт 2)
5. Тяжёлая депрессия, биполяр в смешанном эпизоде, психоз
6. Зависимости (особенно алкоголь)
7. Доступ к средствам (оружие)

### Немедленные меры при высоком риске
- Постоянное наблюдение, не оставлять одного
- Удаление средств (оружие, лекарства)
- Psychiatric emergency evaluation
- Госпитализация (добровольная или недобровольная при отказе)
- Safety plan (Stanley-Brown Safety Planning Intervention)
- Contacts: Национальная кризисная линия

### Ограничения
- Требует активного вопрошания — пациент часто не сообщает сам
- "Нет" ответ не исключает риск — оценивать клинически, с информантами
- Культурные различия в выражении суицидальности`,
};

export default runner;
