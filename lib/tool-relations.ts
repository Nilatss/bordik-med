/**
 * Получить связанные МКБ-10 коды для инструмента.
 * Сначала смотрим override, потом subcategory-mapping; дедуплицируем.
 */
export function getRelatedMkb10(
  toolId: string,
  subcategory: string,
): string[] {
  const fromOverride = TOOL_MKB10_OVERRIDE[toolId];
  const fromSub = SUBCATEGORY_TO_MKB10[subcategory] ?? [];
  const merged = fromOverride !== undefined ? fromOverride : fromSub;
  // Дедуп с сохранением порядка
  return Array.from(new Set(merged));
}

/**
 * URL клин. рекомендации Минздрава по МКБ-10 коду.
 * Рубрикатор cr.minzdrav.gov.ru поддерживает поиск по коду —
 * возвращаем search-страницу. Для будущей версии (когда у нас будет
 * прямой mapping mkb10 → guideline_id) — заменим на конкретные ссылки.
 */
export function minzdravGuidelineSearchUrl(mkb10Code: string): string {
  // Берём только верхнеуровневую категорию (до точки) — рубрикатор
  // принимает 3-знаковый код лучше всего.
  const top = mkb10Code.split('.')[0] ?? mkb10Code;
  return `https://cr.minzdrav.gov.ru/?search=${encodeURIComponent(top)}`;
}
